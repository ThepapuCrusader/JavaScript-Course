//En caso de que quieres transformar un texto completo a minuscula o mayuscula JavaScript tiene metodos para estas situaciones.
//toLowerCase() y toUpperCase() 

//ejemplos

let papu1 = "Goodbye World";
let upperPapu = papu1.toUpperCase();
console.log(upperPapu); //devuelve todo el texto en mayusculas 


let papu2 = "Help me world";
let lowerPapu = papu2.toLowerCase();
console.log(lowerPapu); //devuelve todo el texto en minusculas

//PD: estos dos metodos no modifican la cadena original, en su lugar crean una nueva
